/// Longest question, as for /talk.
const MAX_QUESTION_CHARS: usize = 4_000;
/// Request body of a message: 4,000 characters of up to 4 bytes, escaped as JSON, fit easily.
pub const MAX_MESSAGE_BODY_BYTES: usize = 64 * 1024;
/// The window of WEB_DAILY_MESSAGES_PER_USER.
const DAY: Duration = Duration::from_secs(86_400);
const KEEP_ALIVE: Duration = Duration::from_secs(15);
/// Events waiting for a slow browser (and for the relay from the agent).
const EVENT_BUFFER: usize = 64;
/// Saving how an answer ended gets this long, shutdown or not; so does telling the browser (one
/// that stops reading must not keep the generation slot).
const SAVE_TIMEOUT: Duration = Duration::from_secs(5);
/// Users whose recent questions are remembered before stale ones are swept.
const RECENT_USERS: usize = 1_000;

const NO_USE_RIGHT: &str =
    "このサーバーでチャットを使う権限がありません（サーバー管理者が許可したロールが必要です）。";
const INTERRUPTED: &str = "Botの再起動などにより回答が中断されました。もう一度送信してください。";
const NOT_SAVED: &str = "回答を保存できませんでした。時間をおいて再試行してください。";

/// What the chat keeps in memory (one process): the answers being generated, so that they can
/// be stopped, and each user's recent questions, so that deleting conversations does not reset
/// the daily limit.
pub struct Chat {
    running: Mutex<HashMap<u64, Running>>,
    shutdown: watch::Sender<bool>,
    recent: Mutex<HashMap<u64, VecDeque<Instant>>>,
}

struct Running {
    conversation: u64,
    answer: u64,
    stop: watch::Sender<bool>,
}

impl Default for Chat {
    fn default() -> Self {
        Self {
            running: Mutex::default(),
            shutdown: watch::channel(false).0,
            recent: Mutex::default(),
        }
    }
}

impl Chat {
    /// Stops the user's answer being generated; false if there is none.
    pub fn stop(&self, user: u64) -> bool {
        let running = self.running.lock().expect("chat lock poisoned");
        running
            .get(&user)
            .is_some_and(|run| run.stop.send(true).is_ok())
    }

    /// Ends every answer being generated, saving what each has (the bot is shutting down).
    pub fn shut_down(&self) {
        self.shutdown.send_replace(true);
    }

    fn stop_conversation(&self, user: u64, conversation: u64) {
        let running = self.running.lock().expect("chat lock poisoned");
        if let Some(run) = running.get(&user)
            && run.conversation == conversation
        {
            let _ = run.stop.send(true);
        }
    }

    /// The ID of the user's answer being generated.
    fn running_answer(&self, user: u64) -> Option<u64> {
        let running = self.running.lock().expect("chat lock poisoned");
        running.get(&user).map(|run| run.answer)
    }

    fn register(&self, user: u64, conversation: u64, answer: u64) -> watch::Receiver<bool> {
        let (stop, stopped) = watch::channel(false);
        let mut running = self.running.lock().expect("chat lock poisoned");
        running.insert(
            user,
            Running {
                conversation,
                answer,
                stop,
            },
        );
        stopped
    }

    fn unregister(&self, user: u64, answer: u64) {
        let mut running = self.running.lock().expect("chat lock poisoned");
        if running.get(&user).is_some_and(|run| run.answer == answer) {
            running.remove(&user);
        }
    }

    /// Questions the user sent in the last 24 hours, as far as this process has seen.
    fn recent_questions(&self, user: u64) -> u32 {
        let mut recent = self.recent.lock().expect("chat lock poisoned");
        let Some(times) = recent.get_mut(&user) else {
            return 0;
        };
        forget_old(times);
        let count = times.len() as u32;
        if times.is_empty() {
            recent.remove(&user);
        }
        count
    }

    fn record_question(&self, user: u64) {
        let mut recent = self.recent.lock().expect("chat lock poisoned");
        if recent.len() >= RECENT_USERS {
            recent.retain(|_, times| {
                forget_old(times);
                !times.is_empty()
            });
        }
        recent.entry(user).or_default().push_back(Instant::now());
    }
}

fn forget_old(times: &mut VecDeque<Instant>) {
    while times.front().is_some_and(|at| at.elapsed() >= DAY) {
        times.pop_front();
    }
}

#[derive(Deserialize)]
pub struct GuildQuery {
    guild: Option<String>,
}

#[derive(Serialize)]
pub struct ConversationList {
    conversations: Vec<ConversationView>,
    /// Whether to offer the knowledge base: it is enabled and the guild has ready documents.
    knowledge: bool,
    daily_limit: u32,
    /// Questions sent in the last 24 hours.
    daily_used: u32,
}

#[derive(Serialize)]
pub struct ConversationView {
    id: u64,
    #[serde(with = "id_string")]
    guild_id: u64,
    /// `null` until the first message names it.
    title: Option<String>,
    created_at: DateTime<Utc>,
    updated_at: DateTime<Utc>,
}

#[derive(Serialize)]
pub struct ConversationDetail {
    #[serde(flatten)]
    conversation: ConversationView,
    messages: Vec<MessageView>,
}

#[derive(Serialize)]
pub struct MessageView {
    id: u64,
    /// `user` or `assistant`.
    role: &'static str,
    content: String,
    /// `completed`, `streaming` (being generated now), `failed`, `stopped` or `interrupted`.
    status: &'static str,
    web_search: bool,
    knowledge: bool,
    sources: Vec<Source>,
    kb_sources: Vec<KbSource>,
    tool_count: u32,
    /// Why the answer failed or was interrupted, for the user.
    error: Option<&'static str>,
    created_at: DateTime<Utc>,
}

