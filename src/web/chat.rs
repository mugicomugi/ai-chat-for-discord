//! The web chat: a user's conversations in a guild, with answers streamed as server-sent
//! events. A conversation belongs to its user (another user's is 404). Listing, starting one
//! and sending a message need the right to use the bot in the guild, checked anew every time,
//! so a removed role, a denied guild or one the bot left stops the chat. Answers share /talk's
//! generation limits (one per user, four in all) and run in a task of their own, which ends
//! when the answer is complete, the browser goes away, the user presses stop, the bot shuts down
//! or REQUEST_TIMEOUT_SECONDS pass, and saves what was generated by then.

